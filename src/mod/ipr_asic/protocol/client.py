from collections.abc import Sequence
from typing import Protocol

from mod.ipr_asic.schemas.models import (
    APIObject,
    ContentResponse,
    MinerPoolModel,
    NetworkInfoModel,
    PoolConfig,
    SummaryModel,
    SystemInfoModel,
    VersionInfoModel,
)


class MinerClient(Protocol):
    def version_number(self, version_str: str) -> int: ...
    async def mac_address(self) -> str: ...
    async def hostname(self) -> str: ...
    async def get_version_info(self) -> tuple[str, VersionInfoModel]: ...
    async def get_system_info(self) -> SystemInfoModel: ...
    async def get_network_info(self) -> NetworkInfoModel: ...
    async def summary(self) -> SummaryModel: ...
    async def pools(self) -> Sequence[MinerPoolModel]: ...
    async def get_pool_conf(self) -> PoolConfig: ...
    async def update_pool_conf(
        self, urls: list[str], users: list[str], passwds: list[str]
    ) -> APIObject: ...
    async def update_network_conf(
        self,
        dhcp: bool,
        hostname: str,
        ip: str,
        mask: str,
        gateway: str,
        dns: list[str],
    ) -> APIObject: ...
    async def update_passwd(self, old_passwd: str, new_passwd: str) -> APIObject: ...
    async def get_miner_log(self) -> ContentResponse: ...
    async def get_log_list(self) -> list[str]: ...
    async def download_logs(
        self, log_list: list[str] | None = None
    ) -> ContentResponse: ...
    async def blink(self, enabled: bool) -> APIObject: ...
    async def start(self) -> APIObject: ...
    async def stop(self) -> APIObject: ...
    async def restart(self) -> APIObject: ...
    async def reboot(self) -> APIObject: ...
    async def reset_firmware(self) -> APIObject: ...
    async def rollback_firmware(self) -> APIObject: ...
    async def update_firmware(
        self,
        firmware: bytes,
        filename: str,
        keep_settings: bool,
    ) -> APIObject: ...

    def error(self) -> Exception | None: ...
    def set_error(self, ex: Exception) -> None: ...
    def close(self, ex: Exception | None = None) -> None: ...
